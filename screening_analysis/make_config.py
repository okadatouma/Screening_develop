"""run_2deg_screen.py / run_2deg.py から、設定だけ差し替えたコピーを生成する。

オリジナルは一切書き換えない。置換は各1箇所に当たることを確認し、
外れたら即座に停止する（上流が変わったのに黙って走るのを防ぐ）。

  python screening_analysis/make_config.py --tag soft --batch 1024 \
      --w-factor 1.4 --w-spread 1.4 --trim 1.9 --trim-max 2.0

生成先: periodicwave/configs/run_2deg_screen_<tag>.py
結果フォルダ: results/2deg-Coulomb/<network>/el<N>_rs<r_s>_<shape>_<tag>/
"""
import argparse
import os
import re
import sys

A = argparse.ArgumentParser()
A.add_argument("--tag", required=True, help="結果フォルダとファイル名の接尾辞")
A.add_argument("--batch", type=int, default=1024)
A.add_argument("--w-factor", type=float, default=None, help="遮蔽長の幾何中心 w/d_ref")
A.add_argument("--w-spread", type=float, default=None, help="ヘッド間の散らばり（1.0 で全ヘッド同一）")
A.add_argument("--trim", type=float, default=None, help="Trim 受容幅 r の初期値")
A.add_argument("--trim-max", type=float, default=None, help="2.0=従来 / 1.0=原論文")
A.add_argument("--softmask", choices=["on", "off"], default=None)
A.add_argument("--gate", choices=["on", "off"], default=None)
A.add_argument("--tanh-norm", choices=["on", "off"], default=None)
A.add_argument("--psiformer", action="store_true", help="run_2deg.py を元にする（遮蔽なしの基準）")
a = A.parse_args()

root = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
src = os.path.join(root, "periodicwave", "configs",
                   "run_2deg.py" if a.psiformer else "run_2deg_screen.py")
dst = os.path.join(root, "periodicwave", "configs",
                   ("run_2deg_%s.py" if a.psiformer else "run_2deg_screen_%s.py") % a.tag)
s = open(src, encoding="utf-8").read()


def sub(pattern, repl, label):
    global s
    s, n = re.subn(pattern, repl, s)
    print("    %-22s : %d hit(s)" % (label, n))
    if n != 1:
        sys.exit("PATCH FAILED (%s): expected exactly 1 hit." % label)


sub(r"(?m)^cfg\.batch_size\s*=\s*\d+", "cfg.batch_size = %d" % a.batch, "batch_size")
sub(r'_\{supercell_shape\}"', '_{supercell_shape}_%s"' % a.tag, "folder tag")
if a.w_factor is not None:
    sub(r"'init_softmask_w_factor':\s*[\d.]+", "'init_softmask_w_factor': %g" % a.w_factor, "w_factor")
if a.w_spread is not None:
    sub(r"'init_softmask_w_spread':\s*[\d.]+", "'init_softmask_w_spread': %g" % a.w_spread, "w_spread")
if a.trim is not None:
    sub(r"'init_trim_r':\s*[\d.]+", "'init_trim_r': %g" % a.trim, "init_trim_r")
for val, key, label in ((a.softmask, "use_softmask", "use_softmask"),
                        (a.gate, "use_gate", "use_gate"),
                        (a.tanh_norm, "use_tanh_norm", "use_tanh_norm")):
    if val is not None:
        sub(r"'%s':\s*\w+" % key, "'%s': %s" % (key, val == "on"), label)

if a.trim_max is not None and not a.psiformer:
    s = s.replace("from periodicwave import base_config",
                  "from periodicwave import CustomScreenformer as _CS\n"
                  "_CS.TRIM_MAX = %g\n"
                  "from periodicwave import base_config" % a.trim_max, 1)

open(dst, "w", encoding="utf-8").write(
    "# AUTO-GENERATED by screening_analysis/make_config.py -- do not edit.\n"
    "# %s\n" % vars(a) + s)
print("    ->", os.path.relpath(dst, root))
